#!/usr/bin/env node
// Builds public/press/walkthrough.{mp4,webm} and walkthrough-poster.png:
// about 30 seconds, muted, loops cleanly. Three parts, joined with crossfades:
//
//   1. terminal  a real `conv3d bulk ./models --tsx --optimize -y` run
//                over the KayKit Adventurers FBXs (vhs, walkthrough-terminal.tape)
//   2. code      the generated tsx/Barbarian.tsx with its gltfjsx header
//   3. browser   that component rendered as-is in a react-three-fiber page
//
//   pnpm build                              # repo root: dist/conv3d.js
//   cd docs && pnpm press:walkthrough
//
// Needs vhs, ffmpeg, the KayKit pack (see _press-lib.mjs) and, on Apple
// Silicon, Rosetta for FBX2glTF. SKIP_TERMINAL=1 reuses the last recording.

import { execFileSync } from "node:child_process";
import {
  copyFileSync,
  existsSync,
  mkdirSync,
  mkdtempSync,
  readdirSync,
  readFileSync,
  rmSync,
  writeFileSync,
} from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { chromium } from "@playwright/test";
import { codeToHtml } from "shiki";
import {
  bundle,
  DOCS_DIR,
  MODEL_CREDIT,
  PRESS_DIR,
  requireKaykit,
  run,
  SCRIPTS_DIR,
  serveDirs,
} from "./_press-lib.mjs";

const W = 1920;
const H = 1080;
const FPS = 30;
const CODE_SECONDS = 9.5;
const BROWSER_SECONDS = 11;
const FADE = 0.5;
const MODEL = "Barbarian";

const TERMINAL_MP4 = "/tmp/conv3d-press/terminal.mp4"; // written by walkthrough-terminal.tape
const TERMINAL_END_PNG = "/tmp/conv3d-press/terminal-end.png"; // same, lossless last screen
const OUTPUT_DIR = "/tmp/conv3d-walkthrough/models/_convert-3d-for-web"; // see _walkthrough-setup.sh

requireKaykit();
mkdirSync("/tmp/conv3d-press", { recursive: true });
if (!process.env.SKIP_TERMINAL || !existsSync(TERMINAL_MP4) || !existsSync(TERMINAL_END_PNG)) {
  run("vhs", ["walkthrough-terminal.tape"], { cwd: SCRIPTS_DIR });
}

const work = mkdtempSync(join(tmpdir(), "conv3d-walkthrough-"));
const tsxPath = join(OUTPUT_DIR, "tsx", `${MODEL}.tsx`);
const source = readFileSync(tsxPath, "utf8");
if (!source.includes("Auto-generated by: https://github.com/pmndrs/gltfjsx")) {
  throw new Error(`${tsxPath} has no gltfjsx header; rebuild dist/conv3d.js from main`);
}

// --- 2. code view ----------------------------------------------------------

const tree = ["glb", "glb-for-web", "tsx"]
  .map((dir) => {
    const files = readdirSync(join(OUTPUT_DIR, dir)).sort();
    return `<div class="dir">▾ ${dir}</div>${files
      .map((f) => `<div class="file${f === `${MODEL}.tsx` ? " open" : ""}">${f}</div>`)
      .join("")}`;
  })
  .join("");
const codeHtml = await codeToHtml(source.trimEnd(), { lang: "tsx", theme: "catppuccin-mocha" });

const frame = (title, body) => `<!doctype html>
<meta charset="utf-8">
<style>
  * { box-sizing: border-box; margin: 0; }
  html, body { width: ${W}px; height: ${H}px; overflow: hidden; background: #1e1e2e; color: #cdd6f4;
    font: 20px/1.4 -apple-system, "Inter", "Helvetica Neue", Arial, sans-serif; }
  .bar { height: 48px; display: flex; align-items: center; gap: 9px; padding: 0 18px; background: #181825; }
  .dot { width: 13px; height: 13px; border-radius: 50%; }
  .title { flex: 1; text-align: center; margin-right: 80px; color: #a6adc8; font-size: 18px; }
  .main { position: absolute; top: 48px; left: 0; right: 0; bottom: 0; }
  .mono { font-family: "JetBrains Mono", "SF Mono", Menlo, monospace; }
</style>
<div class="bar"><span class="dot" style="background:#ff5f57"></span><span class="dot" style="background:#febc2e"></span><span class="dot" style="background:#28c840"></span><span class="title">${title}</span></div>
<div class="main">${body}</div>`;

writeFileSync(
  join(work, "code.html"),
  frame(
    "models/_convert-3d-for-web/tsx/Barbarian.tsx",
    `<style>
  .main { display: flex; }
  .side { width: 400px; flex: none; white-space: nowrap; padding: 22px 0; background: #181825; border-right: 1px solid #313244; font-size: 18px; }
  .side .head { padding: 0 22px 12px; color: #7f849c; font-size: 14px; letter-spacing: 0.08em; text-transform: uppercase; }
  .side .dir { padding: 3px 22px; color: #bac2de; }
  .side .file { padding: 3px 22px 3px 44px; color: #7f849c; }
  .side .file.open { background: #313244; color: #f5c2e7; }
  #scroller { flex: 1; overflow: hidden; }
  pre.shiki { margin: 0; padding: 26px 0 60px; background: transparent !important; counter-reset: line;
    font: 22px/34px "JetBrains Mono", "SF Mono", Menlo, monospace; }
  pre.shiki .line { display: inline-block; white-space: pre; }
  pre.shiki .line::before { counter-increment: line; content: counter(line); display: inline-block;
    width: 56px; margin-right: 28px; text-align: right; color: #585b70; }
</style>
<div class="side mono"><div class="head">_convert-3d-for-web</div>${tree}</div>
<div id="scroller">${codeHtml}</div>`,
  ),
);

// --- 3. browser view -------------------------------------------------------

copyFileSync(join(OUTPUT_DIR, "tsx", `${MODEL}.tsx`), join(work, "Model.tsx"));
copyFileSync(
  join(OUTPUT_DIR, "glb-for-web", `${MODEL}-transformed.glb`),
  join(work, `${MODEL}-transformed.glb`),
);
await bundle(join(SCRIPTS_DIR, "_press-r3f-page.tsx"), join(work, "page.js"), {
  "generated-model": join(work, "Model.tsx"),
});
writeFileSync(
  join(work, "index.html"),
  frame(
    "react-three-fiber page rendering &lt;Model /&gt; from tsx/Barbarian.tsx",
    `<style>
  #root { position: absolute; inset: 0; }
  .note { position: absolute; left: 40px; top: 36px; padding: 18px 22px; border-radius: 12px;
    background: rgba(17, 17, 27, 0.82); border: 1px solid #313244; font-size: 22px; line-height: 34px; }
  .k { color: #cba6f7; } .s { color: #a6e3a1; } .t { color: #89b4fa; } .p { color: #9399b2; }
  .credit { position: absolute; left: 40px; bottom: 30px; color: #9399b2; font-size: 20px; }
</style>
<div id="root"></div>
<div class="note mono"><div><span class="k">import</span> { Model } <span class="k">from</span> <span class="s">'./tsx/Barbarian'</span></div>
<div><span class="p">&lt;</span><span class="t">Canvas</span><span class="p">&gt;</span> … <span class="p">&lt;</span><span class="t">Model</span> <span class="p">/&gt;</span> … <span class="p">&lt;/</span><span class="t">Canvas</span><span class="p">&gt;</span></div></div>
<div class="credit">${MODEL_CREDIT}</div>
<script type="module" src="/page.js"></script>`,
  ),
);

// --- capture frames --------------------------------------------------------

const server = await serveDirs({ "/draco/": join(DOCS_DIR, "public", "draco"), "/": work });
const ease = (x) => (x < 0.5 ? 2 * x * x : 1 - (-2 * x + 2) ** 2 / 2);
try {
  const browser = await chromium.launch({ channel: "chromium", headless: true });
  const page = await browser.newPage({ viewport: { width: W, height: H }, deviceScaleFactor: 1 });
  page.on("pageerror", (err) => console.error(err));

  // Code: hold on the gltfjsx header, scroll to the JSX, hold.
  mkdirSync(join(work, "code"));
  await page.goto(`${server.url}/code.html`);
  await page.evaluate(() => document.fonts.ready);
  const maxScroll = await page.evaluate(() => {
    const s = document.getElementById("scroller");
    return s.scrollHeight - s.clientHeight;
  });
  const codeFrames = Math.round(CODE_SECONDS * FPS);
  for (let i = 0; i < codeFrames; i++) {
    const t = i / FPS;
    const k = ease(Math.min(1, Math.max(0, (t - 3.2) / 2.6)));
    await page.evaluate(
      (y) => {
        document.getElementById("scroller").scrollTop = y;
      },
      Math.round(k * maxScroll),
    );
    await page.screenshot({ path: join(work, "code", `${String(i).padStart(4, "0")}.png`) });
  }

  // Browser: step the turntable frame by frame.
  mkdirSync(join(work, "r3f"));
  await page.goto(`${server.url}/index.html`);
  await page.waitForFunction(() => window.__ready === true, null, { timeout: 120_000 });
  const r3fFrames = Math.round(BROWSER_SECONDS * FPS);
  for (let i = 0; i < r3fFrames; i++) {
    await page.evaluate((t) => window.__frame(t), i / (r3fFrames - 1));
    await page.screenshot({ path: join(work, "r3f", `${String(i).padStart(4, "0")}.png`) });
  }
  await browser.close();
} finally {
  server.close();
}

// --- join ------------------------------------------------------------------

const ffmpeg = (args) =>
  execFileSync("ffmpeg", ["-loglevel", "error", "-y", ...args], { stdio: "inherit" });
const termSeconds = Number(
  execFileSync("ffprobe", [
    "-v",
    "error",
    "-show_entries",
    "format=duration",
    "-of",
    "csv=p=0",
    TERMINAL_MP4,
  ])
    .toString()
    .trim(),
);
// The clip ends on the terminal's first frame, so the loop point is invisible.
ffmpeg(["-i", TERMINAL_MP4, "-frames:v", "1", join(work, "first.png")]);

const norm = `fps=${FPS},scale=${W}:${H}:flags=lanczos,format=yuv420p,setsar=1`;
const off1 = termSeconds - FADE;
const off2 = off1 + CODE_SECONDS - FADE;
const off3 = off2 + BROWSER_SECONDS - FADE;
const master = join(work, "master.mp4");
ffmpeg([
  "-i",
  TERMINAL_MP4,
  "-framerate",
  String(FPS),
  "-i",
  join(work, "code", "%04d.png"),
  "-framerate",
  String(FPS),
  "-i",
  join(work, "r3f", "%04d.png"),
  "-loop",
  "1",
  "-t",
  "1.2",
  "-framerate",
  String(FPS),
  "-i",
  join(work, "first.png"),
  "-filter_complex",
  [
    `[0:v]${norm}[a]`,
    `[1:v]${norm}[b]`,
    `[2:v]${norm}[c]`,
    `[3:v]${norm}[d]`,
    `[a][b]xfade=transition=fade:duration=${FADE}:offset=${off1}[ab]`,
    `[ab][c]xfade=transition=fade:duration=${FADE}:offset=${off2}[abc]`,
    `[abc][d]xfade=transition=fade:duration=${FADE}:offset=${off3}[out]`,
  ].join(";"),
  "-map",
  "[out]",
  "-an",
  "-c:v",
  "libx264",
  "-preset",
  "slow",
  "-crf",
  "18",
  master,
]);

mkdirSync(PRESS_DIR, { recursive: true });
const mp4 = join(PRESS_DIR, "walkthrough.mp4");
const webm = join(PRESS_DIR, "walkthrough.webm");
const poster = join(PRESS_DIR, "walkthrough-poster.png");
ffmpeg([
  "-i",
  master,
  "-an",
  "-c:v",
  "libx264",
  "-preset",
  "slow",
  "-crf",
  "22",
  "-pix_fmt",
  "yuv420p",
  "-profile:v",
  "high",
  "-movflags",
  "+faststart",
  mp4,
]);
ffmpeg([
  "-i",
  master,
  "-an",
  "-c:v",
  "libvpx-vp9",
  "-crf",
  "36",
  "-b:v",
  "0",
  "-row-mt",
  "1",
  "-deadline",
  "good",
  "-cpu-used",
  "2",
  webm,
]);
// Poster: the finished terminal run, just before the first crossfade.
copyFileSync(TERMINAL_END_PNG, poster);

rmSync(work, { recursive: true, force: true });
console.log(`wrote ${mp4}\nwrote ${webm}\nwrote ${poster}`);
