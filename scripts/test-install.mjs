#!/usr/bin/env node
/*
 * test-install — run the packed tarball the way a user gets it.
 *
 * tests/ run from a checkout, where pnpm nests gltfjsx under conv3d. npx and
 * project installs hoist it to the top level. That difference hid a broken
 * --json on every route except global installs through 1.0.7. This script
 * packs the tarball, installs it with npm in a temp project, and runs the CLI.
 *
 * It needs the network, so CI and the release script run it, not pre-push.
 */

import assert from "node:assert/strict";
import { spawnSync } from "node:child_process";
import {
  existsSync,
  mkdirSync,
  mkdtempSync,
  readdirSync,
  readFileSync,
  rmSync,
  writeFileSync,
} from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const repoRoot = join(dirname(fileURLToPath(import.meta.url)), "..");

function npm(args, cwd) {
  const r = spawnSync("npm", args, { cwd, encoding: "utf8" });
  assert.equal(r.status, 0, `npm ${args.join(" ")}\n${r.stdout}\n${r.stderr}`);
  return r.stdout;
}

function walk(dir) {
  return readdirSync(dir, { withFileTypes: true }).flatMap((entry) =>
    entry.isDirectory() ? walk(join(dir, entry.name)) : [join(dir, entry.name)],
  );
}

const tmp = mkdtempSync(join(tmpdir(), "conv3d-install-"));
try {
  const [{ filename }] = JSON.parse(
    npm(["pack", "--ignore-scripts", "--json", "--pack-destination", tmp], repoRoot),
  );
  const project = join(tmp, "project");
  mkdirSync(project);
  npm(["init", "-y"], project);
  npm(["install", join(tmp, filename), "--no-audit", "--no-fund"], project);
  assert.ok(
    existsSync(join(project, "node_modules", "gltfjsx")),
    "gltfjsx must be hoisted, or this does not test the npx and project-install layout",
  );

  const conv3d = (args) =>
    spawnSync(join(project, "node_modules", ".bin", "conv3d"), args, {
      cwd: project,
      encoding: "utf8",
    });

  const models = join(project, "models");
  mkdirSync(models);
  writeFileSync(join(models, "tri.obj"), "v 0 0 0\nv 1 0 0\nv 0 1 0\nf 1 2 3\n");
  const converted = conv3d(["bulk", "./models", "--tsx", "--optimize", "-y", "--json"]);
  assert.equal(converted.status, 0, `bulk stderr: ${converted.stderr}`);
  const result = JSON.parse(converted.stdout);
  assert.equal(result.ok, true);
  const [tsxPath, ...moreTsx] = walk(models).filter((file) => file.endsWith(".tsx"));
  assert.ok(tsxPath, "bulk must write a .tsx");
  assert.deepEqual(moreTsx, []);
  const tsx = readFileSync(tsxPath, "utf8");
  assert.match(tsx, /Auto-generated by: https:\/\/github\.com\/pmndrs\/gltfjsx\n/);
  assert.doesNotMatch(tsx, /Files:/);
  assert.ok(!tsx.includes(tmp), "generated .tsx must not contain local paths");
  assert.ok(
    walk(models).some((file) => file.endsWith("tri-transformed.glb")),
    "--optimize must write a transformed .glb",
  );

  const bad = join(project, "bad");
  mkdirSync(bad);
  writeFileSync(
    join(bad, "bad.glb"),
    Buffer.concat([
      Buffer.from("glTF\x02\x00\x00\x00\x20\x00\x00\x00\x08\x00\x00\x00JSON", "latin1"),
      Buffer.from('{"x":1}'),
    ]),
  );
  const failed = conv3d(["tsx-gen", "./bad", "-y", "--json"]);
  assert.equal(failed.status, 2, `tsx-gen stdout: ${failed.stdout}\nstderr: ${failed.stderr}`);
  const failure = JSON.parse(failed.stdout);
  assert.equal(failure.ok, false);
  assert.equal(failure.errors.length, 1);
  assert.deepEqual(
    walk(bad).filter((file) => file.endsWith(".tsx")),
    [],
  );

  console.log("test-install: tarball works in a project install");
} finally {
  rmSync(tmp, { recursive: true, force: true });
}
